    def plugin_say(self, instruction: str) -> None:
        """
        Thread-safe speech channel for plugins: lets a plugin ask AURA to
        say something short WHILE its run() is still executing (plugins block
        their executor thread, so they can't speak through the tool response
        until they finish). The instruction is injected into the Live session
        exactly like a proactive check-in; Gemini phrases it naturally in the
        user's language. Silently a no-op when no session is connected.
        """
        loop = getattr(self, "_loop", None)
        if not loop or not self.session:
            return

        async def _say():
            try:
                await self.session.send_client_content(
                    turns={"parts": [{"text": instruction}]},
                    turn_complete=True,
                )
            except Exception as e:
                print(f"[PluginSay] {e}")

        try:
            asyncio.run_coroutine_threadsafe(_say(), loop)
        except Exception as e:
            print(f"[PluginSay] {e}")

    def _make_remote_key(self):
        """Called from Qt main thread when user presses Remote Control."""
        if self._dashboard is None:
            self.ui.write_log(
                "SYS: Dashboard unavailable. "
                "Run: pip install fastapi \"uvicorn[standard]\" cryptography"
            )
            return None
        key    = self._dashboard.new_key()
        url    = self._dashboard.get_url()
        manual = self._dashboard.get_manual_url()
        return url, key, f"{url}/auto-login?key={key}", manual

    def _on_text_command(self, text: str):
        if self._hermes:
            threading.Thread(
                target=self._run_hermes_command,
                args=(text,),
                daemon=True,
            ).start()
            return
        if not self._loop or not self.session:
            self.ui.write_log("SYS: No command engine is connected.")
            return
        asyncio.run_coroutine_threadsafe(
            self.session.send_client_content(
                turns={"parts": [{"text": text}]},
                turn_complete=True
            ),
            self._loop
        )

    def _run_hermes_command(self, text: str) -> None:
        """Let Hermes handle local file commands before using the live model."""
        try:
            result = self._hermes.execute(text, player=self.ui)
        except Exception as error:
            result = f"Hermes failed: {error}"

        if result is None:
            if self._loop and self.session:
                asyncio.run_coroutine_threadsafe(
                    self.session.send_client_content(
                        turns={"parts": [{"text": text}]},
                        turn_complete=True,
                    ),
                    self._loop,
                )
            else:
                self.ui.write_log("SYS: No live model is connected for this command.")
            return

        self.ui.write_log(f"Hermes: {result}")
        self.speak(result)

    def set_speaking(self, value: bool):
        with self._speaking_lock:
            self._is_speaking = value
        if value:
            self.ui.set_state("SPEAKING")
        elif not self.ui.muted:
            self.ui.set_state("LISTENING")

    def interrupt(self) -> None:
        """Stop AURA mid-speech: drain queued audio and open mic immediately."""
        self._interrupted = True
        q = self.audio_in_queue
        if q:
            drained = 0
            while True:
                try:
                    q.get_nowait()
                    drained += 1
                except Exception:
                    break
            if drained:
                print(f"[AURA] ✋ Interrupted — {drained} audio chunks discarded")
        self.set_speaking(False)
        if self._turn_done_event:
            self._turn_done_event.clear()
        self.ui.write_log("SYS: Interrupted — listening...")

    def speak(self, text: str):
        if not self._loop or not self.session:
            return
        asyncio.run_coroutine_threadsafe(
            self.session.send_client_content(
                turns={"parts": [{"text": text}]},
                turn_complete=True
            ),
            self._loop
        )

    def speak_error(self, tool_name: str, error: str):
        short = str(error)[:120]
        self.ui.write_log(f"ERR: {tool_name} — {short}")
        self.speak(f"Sir, {tool_name} encountered an error. {short}")

    def _build_config(self) -> types.LiveConnectConfig:
        from datetime import datetime

        # Load customization from config
        try:
            _cfg = json.loads(open(API_CONFIG_PATH, encoding="utf-8").read())
            self._asst_name = (_cfg.get("assistant_name") or "AURA").strip()
            _user_name = (_cfg.get("user_name") or "").strip()
        except Exception:
            self._asst_name = "AURA"
            _user_name = ""

        memory     = load_memory()
        mem_str    = format_memory_for_prompt(memory)
        sys_prompt = _load_system_prompt()

        now      = datetime.now()
        time_str = now.strftime("%A, %B %d, %Y — %I:%M %p")
        time_ctx = (
            f"[CURRENT DATE & TIME]\n"
            f"Right now it is: {time_str}\n"
            f"Use this to calculate exact times for reminders.\n\n"
        )

        # Identity injection — overrides any hardcoded name in prompt.txt
        _addr = (f"ADDRESS: Always call the user '{_user_name}'."
                 if _user_name
                 else "ADDRESS: When speaking English → say \"sir\". "
                      "When speaking Hindi → say \"जी\". Never mix languages.")
        identity_ctx = (
            f"[IDENTITY]\n"
            f"Your name is {self._asst_name}. "
            f"Always refer to yourself as {self._asst_name}.\n"
            f"{_addr}\n\n"
        )

        parts = [time_ctx, identity_ctx]
        if mem_str:
            parts.append(mem_str)
        parts.append(sys_prompt)

        cfg = dict(
            response_modalities=["AUDIO"],
            output_audio_transcription={},
            input_audio_transcription={},
            system_instruction="\n".join(parts),
            tools=[{"function_declarations": TOOL_DECLARATIONS + self._plugin_registry.get_tool_declarations()}],
            # Thinking tokens are generated before the first audio byte, so
            # they land entirely in the user-visible pause. The logs showed
            # 'thought' parts coming back on every turn; switching them off
            # measured ~575 ms faster to first audio. A live voice assistant
            # answering conversationally does not need them.
            thinking_config=types.ThinkingConfig(
                thinking_budget=0, include_thoughts=False),
            session_resumption=types.SessionResumptionConfig(
                handle=self._resume_handle),
            # Sliding-window compression: session never dies from a full context
            # window — AURA can stay in one conversation for hours
            context_window_compression=types.ContextWindowCompressionConfig(
                sliding_window=types.SlidingWindow(),
            ),
            speech_config=types.SpeechConfig(
                voice_config=types.VoiceConfig(
                    prebuilt_voice_config=types.PrebuiltVoiceConfig(
                        voice_name="Charon"
                    )
                )
            ),
        )
        if self._advanced_input:
            # Explicit turn-taking. Left unset, the session runs on defaults
            # that never let a new utterance cut an in-flight reply short,
            # which is what made interruptions feel unresponsive even once the
            # microphone was held open.
            cfg["realtime_input_config"] = types.RealtimeInputConfig(
                automatic_activity_detection=types.AutomaticActivityDetection(
                    # Start eagerly, end patiently: a missed word at the start
                    # of a sentence is unrecoverable, whereas ending a turn a
                    # beat early cuts the user off mid-thought.
                    start_of_speech_sensitivity=types.StartSensitivity.START_SENSITIVITY_HIGH,
                    end_of_speech_sensitivity=types.EndSensitivity.END_SENSITIVITY_HIGH,
                    # Carry the audio just before detection into the turn, so
                    # the first syllable is not clipped.
                    prefix_padding_ms=200,
                    # This is pure added latency on every single turn: the
                    # assistant cannot start until the silence has elapsed.
                    # 550 ms still tolerates a beat of hesitation while cutting
                    # ~350 ms off every reply. Raise it if you get cut off
                    # mid-sentence.
                    silence_duration_ms=550,
                ),
                # Speaking over the assistant stops it immediately.
                activity_handling=types.ActivityHandling.START_OF_ACTIVITY_INTERRUPTS,
                turn_coverage=types.TurnCoverage.TURN_INCLUDES_ONLY_ACTIVITY,
            )
            cfg["input_audio_transcription"] = types.AudioTranscriptionConfig(
                # Naming the expected languages sharply improves recognition of
                # code-switched speech, which is the normal case here.
                language_codes=["en-IN", "hi-IN", "en-US"],
            )

        if self._enhanced_live:
            # Affective dialog: AURA hears tone/emotion and adapts its voice.
            # Proactive audio: AURA stays silent when speech isn't addressed
            # to it (background chatter, talking to someone else in the room).
            cfg["enable_affective_dialog"] = True
            cfg["proactivity"] = types.ProactivityConfig(proactive_audio=True)
        return types.LiveConnectConfig(**cfg)

