# ── Run from anywhere ────────────────────────────────────────────────────────
# `python main.py` should just start AURA, whichever interpreter "python"
# happens to be. The dependencies live in the project's .venv, so if the
# current interpreter cannot see them this re-executes inside the venv,
# creating and populating it first when it does not exist yet. Guarded by an
# environment variable so a genuinely broken install fails with a real error
# instead of re-launching itself forever.
def _bootstrap() -> None:
    import os
    from pathlib import Path

    if os.environ.get("AURA_BOOTSTRAPPED") == "1":
        return

    root = Path(__file__).resolve().parent
    venv = root / ".venv"
    exe  = venv / ("Scripts/python.exe" if os.name == "nt" else "bin/python")

    # Already running inside the project venv - nothing to do.
    try:
        if exe.exists() and Path(_sys.executable).resolve() == exe.resolve():
            return
    except OSError:
        pass

    # Deliberately NOT "can I import google.genai?". The system interpreter has
    # an older copy of it installed, so that check passed and AURA started
    # against stale libraries - then died on a config field the old version
    # does not know. Whether an import succeeds says nothing about whether it
    # is the *right* version. If the project venv exists, it is the answer.
    if not exe.exists():
        try:
            import google.genai, PyQt6, sounddevice   # noqa: F401
            return          # no venv, but this interpreter is fully equipped
        except ImportError:
            pass

    if not exe.exists():
        print("[AURA] First run - creating the virtual environment...")
        _subprocess.run([_sys.executable, "-m", "venv", str(venv)], check=True)
        print("[AURA] Installing dependencies (a few minutes, once)...")
        _subprocess.run([str(exe), "-m", "pip", "install", "-q", "--upgrade", "pip"])
        _subprocess.run([str(exe), "-m", "pip", "install", "-r",
                         str(root / "requirements.txt")], check=True)
        _subprocess.run([str(exe), "-m", "playwright", "install", "chromium"])

    env = dict(os.environ, AURA_BOOTSTRAPPED="1")
    print("[AURA] Starting in the project environment...")
    raise SystemExit(_subprocess.call([str(exe), str(Path(__file__).resolve()),
                                       *_sys.argv[1:]], env=env))


_bootstrap()

# ── Make stdout/stderr UTF-8 tolerant ────────────────────────────────────────
# On non-UTF-8 Windows consoles (cp1254/cp1252/cp936...) any print() containing
# an emoji raises UnicodeEncodeError.  Several of those prints sit inside except
# handlers, so the handler itself would blow up and skip the recovery code that
# follows it — turning a recoverable error into a silent hang.  errors="replace"
# makes every print safe.
for _stream in (_sys.stdout, _sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass   # frozen builds may have no real stream attached

# ── Nuclear: force CREATE_NO_WINDOW on EVERY subprocess call on Windows ───────
# This patches Popen itself, so no per-file flag is needed anywhere.
if _platform.system() == "Windows":
    _OrigPopen = _subprocess.Popen

    class _Popen(_OrigPopen):
        def __init__(self, args, **kw):
            kw["creationflags"] = kw.get("creationflags", 0) | _subprocess.CREATE_NO_WINDOW
            kw.pop("startupinfo", None)   # drop any stale/shared STARTUPINFO
            super().__init__(args, **                       kw)

    _subprocess.Popen = _Popen

