def _normalize(raw: str) -> str:
    """Map a spoken name onto this OS's launch target via the alias table.

    Only exact and whole-word matches count. The previous version accepted any
    substring in either direction, so `key in alias_key` matched a two-letter
    query against half the table - "am" resolved to Steam, and anything
    containing "code" became VS Code.
    """
    key = raw.lower().strip()

    if key in _APP_ALIASES:
        return _APP_ALIASES[key].get(_SYSTEM, raw)

    words = set(key.split())
    for alias_key, os_map in _APP_ALIASES.items():
        alias_words = set(alias_key.split())
        if alias_words and alias_words <= words:
            return os_map.get(_SYSTEM, raw)

    return raw

def _launch_windows(app_name: str) -> bool:

    if shutil.which(app_name) or shutil.which(app_name.split(".")[0]):
        try:
            subprocess.Popen(
                app_name,
                shell=True,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            time.sleep(1.5)
            return True
        except Exception as e:
            print(f"[open_app] subprocess failed: {e}")

    if ":" in app_name:
        try:
            subprocess.Popen(f"start {app_name}", shell=True)
            time.sleep(1.0)
            return True
        except Exception:
            pass

    # No Start-menu keystroke simulation here any more. Pressing Win, typing a
    # name and hitting Enter assumes the menu won the race for focus; when it
    # did not, the app name went into whatever window was focused - and Enter
    # after it. The app index replaces it with an actual lookup.
    return False


def _launch_macos(app_name: str) -> bool:

    try:
        result = subprocess.run(
            ["open", "-a", app_name],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    try:
        result = subprocess.run(
            ["open", "-a", f"{app_name}.app"],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    binary = shutil.which(app_name) or shutil.which(app_name.lower())
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        import pyautogui
        pyautogui.hotkey("command", "space")
        time.sleep(0.6)
        pyautogui.write(app_name, interval=0.05)
        time.sleep(0.8)
        pyautogui.press("enter")
        time.sleep(1.5)
        return True
    except Exception as e:
        print(f"[open_app] Spotlight failed: {e}")

    return False


_LINUX_TERMINAL_FALLBACKS = [
    "x-terminal-emulator", "gnome-terminal", "konsole", "xfce4-terminal",
    "xterm", "lxterminal", "mate-terminal", "tilix", "alacritty", "kitty",
]

def _launch_linux(app_name: str) -> bool:

    # terminal emulators: try common ones in order
    if app_name in ("x-terminal-emulator", "gnome-terminal", "terminal"):
        for term in _LINUX_TERMINAL_FALLBACKS:
            if shutil.which(term):
                try:
                    subprocess.Popen([term], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    time.sleep(1.0)
                    return True
                except Exception:
                    continue

    binary = (
        shutil.which(app_name) or
        shutil.which(app_name.lower()) or
        shutil.which(app_name.lower().replace(" ", "-")) or
        shutil.which(app_name.lower().replace(" ", "_"))
    )
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        subprocess.run(
            ["xdg-open", app_name],
            capture_output=True, timeout=5
        )
        return True
    except Exception:
        pass

    for desktop_name in [
        app_name.lower(),
        app_name.lower().replace(" ", "-"),
        app_name.lower().replace(" ", ""),
    ]:
        try:
            result = subprocess.run(
                ["gtk-launch", desktop_name],
                capture_output=True, timeout=5
            )
            if result.returncode == 0:
                return True
        except Exception:
            pass

    return False


_OS_LAUNCHERS = {
    "Windows": _launch_windows,
    "Darwin":  _launch_macos,
    "Linux":   _launch_linux,
}

def open_app(
    parameters=None,
    response=None,
    player=None,
    session_memory=None,
) -> str:
    """Open any installed application.

    Resolution order, most reliable first:

      1. the app index - every Start-menu shortcut, Store app, App Paths entry
         and PATH executable on this machine (actions/app_index.py);
      2. the alias table, for spoken names whose launch target differs from
         what people say ("task manager" -> taskmgr.exe);
      3. the raw name, in case it is a command that happens to be on PATH.

    The index goes first because it is the only step that knows what is
    actually installed. Nothing here guesses: when no match clears the
    confidence bar the user is told the app was not found, rather than having
    something adjacent opened silently.
    """
    app_name = (parameters or {}).get("app_name", "").strip()

    if not app_name:
        return "No application name provided."

    # Honour the hint the not-found message gives out.
    if re.fullmatch(r"(refresh|rebuild|update|reindex|re-index)\s+"
                    r"(the\s+)?(app|apps|app index|application list)",
                    app_name, re.I):
        return refresh_index()

    launcher = _OS_LAUNCHERS.get(_SYSTEM)
    if launcher is None:
        return f"Unsupported operating system: {_SYSTEM}"

    if player:
        player.write_log(f"[open_app] {app_name}")

    # -- 1. the index ------------------------------------------------------
    try:
        from actions import app_index

        matches = app_index.resolve(app_name, limit=3)
        if matches:
            app, score = matches[0]
            print(f"[open_app] '{app_name}' -> '{app.name}' "
                  f"({score:.2f}, {app.source})")
            if app_index.launch(app):
                # A confident match speaks for itself. A loose one names what
                # was actually opened, so a wrong guess is obvious and can be
                # corrected instead of quietly being the wrong app.
                if score >= 0.9 or app.name.lower() == app_name.lower():
                    return f"Opened {app.name}."
                return f"Opened {app.name} - the closest match to '{app_name}'."
    except Exception as e:
        print(f"[open_app] index lookup failed: {e}")

    # -- 2. alias table, 3. raw name ---------------------------------------
    normalized = _normalize(app_name)
    print(f"[open_app] falling back: '{app_name}' -> '{normalized}' ({_SYSTEM})")

    try:
        if launcher(normalized):
            return f"Opened {app_name}."
        if normalized.lower() != app_name.lower() and launcher(app_name):
            return f"Opened {app_name}."
    except Exception as e:
        print(f"[open_app] Error: {e}")

    return (f"I could not find an app called '{app_name}' on this machine. "
            f"If you just installed it, say 'refresh apps' and try again.")


def refresh_index() -> str:
    """Rebuild the installed-app index - after installing something new."""
    try:
        from actions import app_index
        return f"Re-indexed {app_index.refresh()} applications."
    except Exception as e:
        return f"Could not refresh the app index: {e}"
